#!/usr/bin/env python3
"""Build packages/census/pep_2025_state_age_bands from the pinned Census file.

Census Vintage 2025 SC-EST2025-ALLDATA6 gives each state's resident population
by single year of age (0 to 84, then 85 and over), sex, Hispanic origin and six
race groups that partition the population. The package selects, for each of
the 50 states and the District of Columbia, the both-sexes, all-origins rows of
the six race groups at every age, in age-major order, and declares each age
group as the contiguous block of those rows Chronicle sums at build time. The
script reads the file only to check that every selected row exists exactly
once; it computes no value. Run it with the repository's environment.
"""

from __future__ import annotations

import csv
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[3]
ARTIFACT = ROOT / "db/data/census/pep_2025_age_sex/sc-est2025-alldata6.csv"
OUT = ROOT / "packages/census/pep_2025_state_age_bands/source_package.yaml"

PACKAGE_ID = "census-pep-2025-state-age-bands"
VINTAGE = 2025
PERIOD = 2024
MEASURE_COLUMN = "O"
MEASURE_HEADER = f"POPESTIMATE{PERIOD}"
SHEET_NAME = "sc-est2025-alldata6"
TOP_AGE = 85
RACES = (1, 2, 3, 4, 5, 6)
ROWS_PER_AGE = len(RACES)
ROWS_PER_STATE = (TOP_AGE + 1) * ROWS_PER_AGE
FIRST_DATA_ROW = 2

# (value id, label, first age, last age); the last age 85 means 85 and over.
# Single years 0 to 5 reuse the ids and labels Census population projection
# packages give the same ages.
AGE_GROUPS = (
    ("age_0", "Age 0", 0, 0),
    ("age_1", "Age 1", 1, 1),
    ("age_2", "Age 2", 2, 2),
    ("age_3", "Age 3", 3, 3),
    ("age_4", "Age 4", 4, 4),
    ("age_5", "Age 5", 5, 5),
    ("6_to_11", "Age 6 to 11", 6, 11),
    ("12_to_17", "Age 12 to 17", 12, 17),
    ("18_to_24", "Age 18 to 24", 18, 24),
    ("25_to_34", "Age 25 to 34", 25, 34),
    ("35_to_44", "Age 35 to 44", 35, 44),
    ("45_to_54", "Age 45 to 54", 45, 54),
    ("55_to_64", "Age 55 to 64", 55, 64),
    ("65_to_74", "Age 65 to 74", 65, 74),
    ("75_plus", "Age 75 plus", 75, TOP_AGE),
)

HEADER = """\
# Generated by packages/census/pep_2025_state_age_bands/build_package.py.
#
# Census Vintage 2025 SC-EST2025-ALLDATA6 (released June 2026): July 1, 2024
# resident population of each state and the District of Columbia, in all and
# in fifteen age groups that partition it: single years 0 to 5, then 6 to 11,
# 12 to 17, 18 to 24, ten-year groups from 25 to 34 through 55 to 64, 65 to 74,
# and 75 and over. Each group sums the both-sexes, all-origins rows of the six
# race groups (five race-alone groups and two or more races) at its ages.
"""


def _states() -> list[tuple[int, str]]:
    """(FIPS, name) of every state-level row block, in file order."""

    seen: dict[int, str] = {}
    counts: dict[tuple[int, int, int], int] = {}
    with ARTIFACT.open(newline="", encoding="utf-8") as stream:
        for row in csv.DictReader(stream):
            if row["SUMLEV"] != "040" or row["SEX"] != "0" or row["ORIGIN"] != "0":
                continue
            fips = int(row["STATE"])
            seen.setdefault(fips, row["NAME"])
            key = (fips, int(row["RACE"]), int(row["AGE"]))
            counts[key] = counts.get(key, 0) + 1
    states = sorted(seen.items())
    if len(states) != 51:
        raise ValueError(f"Expected 50 states and DC, found {len(states)}.")
    for fips, _name in states:
        for race in RACES:
            for age in range(TOP_AGE + 1):
                if counts.get((fips, race, age)) != 1:
                    raise ValueError(
                        f"State {fips:02d} race {race} age {age} has "
                        f"{counts.get((fips, race, age), 0)} total rows."
                    )
    return states


def _guard(column: str, row: str, value: int, label: str) -> dict:
    return {"column": column, "row": row, "expected_value": value, "label": label}


def _block_guards(fips: int) -> list[dict]:
    guards = []
    for column, value, label in (
        ("A", 40, "state summary level"),
        ("D", fips, "state FIPS"),
        ("F", 0, "all sexes"),
        ("G", 0, "all Hispanic origins"),
    ):
        guards.append(_guard(column, "start", value, label))
        guards.append(_guard(column, "end", value, label))
    return guards


def _age_constraints(first: int, last: int) -> list[dict]:
    constraints = [
        {
            "variable": "age",
            "operator": ">=",
            "value": first,
            "unit": "years",
            "label": "Age lower bound",
        }
    ]
    if last < TOP_AGE:
        constraints.append(
            {
                "variable": "age",
                "operator": "<",
                "value": last + 1,
                "unit": "years",
                "label": "Age upper bound",
            }
        )
    return constraints


def _row_label_guards(first: int, last: int) -> list[dict]:
    ages = range(first, last + 1)
    return [
        {
            "column": "I",
            "expected_values": [age for age in ages for _race in RACES],
            "label": "single-year age sequence across six race groups",
        },
        {
            "column": "H",
            "expected_values": [race for _age in ages for race in RACES],
            "label": "six race groups at each age",
        },
    ]


def _rows(state_index: int, fips: int) -> list[dict]:
    start = FIRST_DATA_ROW + state_index * ROWS_PER_STATE
    rows = [
        {
            "value_id": "all",
            "label": "All ages",
            "ordinal": 0,
            "row_number": start,
            "row_end_number": start + ROWS_PER_STATE - 1,
            "expected_row_header_column": "I",
            "expected_row_header": 0,
            "table_record_kind": "total",
            "guard_cells": [
                *_block_guards(fips),
                _guard("I", "end", TOP_AGE, "age 85 plus"),
            ],
        }
    ]
    for ordinal, (value_id, label, first, last) in enumerate(AGE_GROUPS, start=1):
        rows.append(
            {
                "value_id": value_id,
                "label": label,
                "ordinal": ordinal,
                "row_number": start + first * ROWS_PER_AGE,
                "row_end_number": start + (last + 1) * ROWS_PER_AGE - 1,
                "expected_row_header_column": "I",
                "expected_row_header": first,
                "table_record_kind": "detail",
                "guard_cells": _block_guards(fips),
                "constraints": _age_constraints(first, last),
                "range_label_guards": _row_label_guards(first, last),
            }
        )
    return rows


def _record_set(state_index: int, fips: int, name: str) -> dict:
    record_set_id = (
        f"census_pep.v{VINTAGE}.cy{PERIOD}.state_resident_population_age_bands."
        f"{fips:02d}"
    )
    return {
        "record_set_id": record_set_id,
        "provenance_class": "census",
        "record_set_spec_id": (
            f"census_pep.v{VINTAGE}.state_resident_population_age_bands.v1"
        ),
        "source_record_id_prefix": record_set_id,
        "sheet_name": SHEET_NAME,
        "period_type": "calendar_year",
        "period": PERIOD,
        "geography_id": f"0400000US{fips:02d}",
        "geography_level": "state",
        "geography_name": name,
        "geography_vintage": str(VINTAGE),
        "entity": "person",
        "entity_role": "resident_population",
        "domain": "resident_population",
        "groupby_dimension": "age",
        "rows": _rows(state_index, fips),
        "measures": [
            {
                "measure_id": "population",
                "label": "Resident population",
                "ordinal": 0,
                "column": MEASURE_COLUMN,
                "source_column_id": MEASURE_HEADER,
                "expected_column_header_row": 1,
                "expected_column_header": MEASURE_HEADER,
                "concept": "census_pep.resident_population",
                "source_concept": f"census_pep.{MEASURE_HEADER}",
                "concept_relation": "source_label",
                "concept_authority": "census",
                "unit": "count",
                "aggregation": "sum",
                "expected_cell_type": "number",
            }
        ],
    }


def build() -> dict:
    states = _states()
    selected_rows = [
        {"STATE": fips, "SEX": 0, "ORIGIN": 0, "RACE": race, "AGE": age}
        for fips, _name in states
        for age in range(TOP_AGE + 1)
        for race in RACES
    ]
    return {
        "schema_version": "ledger.source_package.v1",
        "package_id": PACKAGE_ID,
        "label": "Census PEP Vintage 2025 state resident population by age group",
        "dimension_labels": {"age": "Age"},
        "artifact": {
            "source_name": "census_pep",
            "source_table": (
                "Annual State Resident Population Estimates for 6 Race Groups "
                "(5 Race Alone Groups and Two or More Races) by Age, Sex, and "
                "Hispanic Origin: April 1, 2020 to July 1, 2025 "
                "(SC-EST2025-ALLDATA6)"
            ),
            "resource_package": "db",
            "resource_directory": "data/census/pep_2025_age_sex",
            "manifest": "manifest_state_source_package.yaml",
            "vintage": f"census_pep_vintage_{VINTAGE}",
            "extracted_at": "2026-11-05",
            "extraction_method": (
                "delimited text full-row parse with selected state age/race "
                "source-row cells"
            ),
            "parser": "delimited_text_full_rows",
            "sheet_name": SHEET_NAME,
            "artifact_year": VINTAGE,
            "selected_rows": selected_rows,
        },
        "record_sets": [
            _record_set(index, fips, name) for index, (fips, name) in enumerate(states)
        ],
    }


def main() -> None:
    package = build()
    OUT.write_text(
        HEADER + yaml.safe_dump(package, sort_keys=False, width=88),
        encoding="utf-8",
    )
    print(
        f"wrote {OUT.relative_to(ROOT)}: {len(package['record_sets'])} record "
        f"sets, {sum(len(r['rows']) for r in package['record_sets'])} rows"
    )


if __name__ == "__main__":
    main()
