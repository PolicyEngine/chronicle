#!/usr/bin/env python3
"""Build packages/census/acs_s1501_state_2024 from the pinned Census JSON.

Row numbers come from the repository's own parser, so the YAML addresses the
exact unpivoted source rows the build will parse. The script declares cells and
their universes; it does not aggregate, reconcile, age or impute. Run it with
the repository's environment (it imports ``chronicle``).
"""

from __future__ import annotations

from pathlib import Path

import yaml

from chronicle.sources.cells import SourceArtifactMetadata
from chronicle.sources.rows import (
    S1501_ATTAINMENT_COLUMNS,
    source_rows_from_census_acs_s1501_attainment_json,
)

ROOT = Path(__file__).resolve().parents[3]
ARTIFACT = ROOT / "db/data/census/acs_s1501_state_2024/acs_S1501_state_2024.json"
OUT = ROOT / "packages/census/acs_s1501_state_2024/source_package.yaml"

LABELS = {
    "all": "Total",
    "less_than_high_school_graduate": "Less than high school graduate",
    "high_school_graduate_includes_equivalency": "High school graduate (includes equivalency)",
    "some_college_or_associates_degree": "Some college or associate's degree",
    "bachelors_degree_or_higher": "Bachelor's degree or higher",
    "less_than_9th_grade": "Less than 9th grade",
    "9th_to_12th_grade_no_diploma": "9th to 12th grade, no diploma",
    "some_college_no_degree": "Some college, no degree",
    "associates_degree": "Associate's degree",
    "bachelors_degree": "Bachelor's degree",
    "graduate_or_professional_degree": "Graduate or professional degree",
}
UNIVERSES = {
    "Aged 18 to 24": (
        "18_to_24",
        [
            {
                "variable": "age",
                "operator": ">=",
                "value": 18,
                "unit": "years",
                "label": "Age lower bound",
            },
            {
                "variable": "age",
                "operator": "<",
                "value": 25,
                "unit": "years",
                "label": "Age upper bound",
            },
        ],
    ),
    "Aged 25 and over": (
        "25_plus",
        [
            {
                "variable": "age",
                "operator": ">=",
                "value": 25,
                "unit": "years",
                "label": "Age lower bound",
            },
        ],
    ),
}

HEADER = """\
# Generated by packages/census/acs_s1501_state_2024/build_package.py.
#
# Census ACS 2024 1-year subject table S1501 (Educational Attainment), Total
# estimate columns (S1501_C01_*), for the 50 states, the District of Columbia
# and Puerto Rico. Latest ACS 1-year vintage: on 2026-10-12 neither
# api.census.gov nor data.census.gov serves 2025 ACS 1-year tables (the Census
# Bureau's 6 August 2026 update says their release date "is being determined").
#
# Source: the data.census.gov table API, which wraps the api.census.gov
# group(S1501) array in {"response": {"data": [...]}}. api.census.gov now
# redirects unkeyed requests to its missing-key page.
#
# Two population universes, kept as published:
# - Population 18 to 24 years (S1501_C01_001E to 005E): four categories. This
#   universe does not separate associate's degrees from "Some college".
# - Population 25 years and over (S1501_C01_006E to 013E): seven categories,
#   with associate's, bachelor's and graduate or professional degrees separate.
# Each universe total is a total row; the categories are detail rows that sum
# to it in this release. Not included: the cumulative "or higher" rows, the
# 25-34/35-44/45-64/65+ summary rows, race and Hispanic origin rows, poverty
# rates, median earnings, percent and sex columns, and margins of error.
"""


def main() -> None:
    artifact = SourceArtifactMetadata(
        source_name="census_acs",
        source_table="generator",
        source_file=ARTIFACT.name,
        url="",
        vintage="",
        sha256="",
        size_bytes=0,
        extracted_at="",
        extraction_method="",
    )
    rows = source_rows_from_census_acs_s1501_attainment_json(
        ARTIFACT.read_bytes(), artifact, sheet_name="api_response"
    )
    per_state = len(S1501_ATTAINMENT_COLUMNS)
    assert len(rows) % per_state == 0
    record_sets = []
    for start in range(0, len(rows), per_state):
        state_rows = rows[start : start + per_state]
        geo_id = state_rows[0].values["GEO_ID"]
        name = state_rows[0].values["NAME"]
        fips = geo_id.removeprefix("0400000US")
        assert geo_id.startswith("0400000US") and len(fips) == 2, geo_id
        for age_label, (universe, shared_constraints) in UNIVERSES.items():
            universe_rows = []
            for offset, source_row in enumerate(state_rows):
                values = source_row.values
                if values["age"] != age_label:
                    continue
                assert values["GEO_ID"] == geo_id and values["NAME"] == name
                attainment = values["educational_attainment"]
                cell_row = start + offset + 2  # header is row 1
                row = {
                    "value_id": attainment,
                    "label": LABELS[attainment],
                    "ordinal": len(universe_rows),
                    "row_number": cell_row,
                    "table_record_kind": "total" if attainment == "all" else "detail",
                    "expected_row_header_column": "F",
                    "expected_row_header": values["source_concept"],
                    "guard_cells": [
                        {"column": "A", "expected_value": geo_id, "label": "GEO_ID"},
                        {"column": "B", "expected_value": name, "label": "State name"},
                        {
                            "column": "C",
                            "expected_value": age_label,
                            "label": "Age universe",
                        },
                        {
                            "column": "D",
                            "expected_value": attainment,
                            "label": "Educational attainment",
                        },
                        {
                            "column": "E",
                            "expected_value": values["source_column_id"],
                            "label": "Census variable",
                        },
                    ],
                }
                if attainment != "all":
                    row["constraints"] = [
                        {
                            "variable": "educational_attainment",
                            "operator": "==",
                            "value": attainment,
                            "label": "Educational attainment",
                        }
                    ]
                universe_rows.append(row)
            record_set_id = (
                f"census_acs.acs1_{{year}}.s1501.state_attainment_{universe}.{fips}"
            )
            record_sets.append(
                {
                    "record_set_id": record_set_id,
                    "provenance_class": "survey_aggregate",
                    "survey_instrument": "ACS 1-year",
                    "record_set_spec_id": f"census_acs.s1501.state_attainment_{universe}.v1",
                    "source_record_id_prefix": record_set_id,
                    "sheet_name": "api_response",
                    "period_type": "calendar_year",
                    "period": "{year}",
                    "geography_id": geo_id,
                    "geography_level": "state",
                    "geography_name": name,
                    "geography_vintage": "current",
                    "entity": "person",
                    "entity_role": "resident_population",
                    "domain": "educational_attainment",
                    "groupby_dimension": "educational_attainment",
                    "shared_constraints": shared_constraints,
                    "rows": universe_rows,
                    "measures": [
                        {
                            "measure_id": "population",
                            "label": "Population",
                            "ordinal": 0,
                            "column": "G",
                            "source_column_id": "value",
                            "expected_column_header_row": 1,
                            "expected_column_header": "value",
                            "concept": "census_acs.person_count",
                            "source_concept": "ACS S1501 educational attainment estimate",
                            "concept_relation": "source_label",
                            "unit": "count",
                            "aggregation": "sum",
                            "expected_cell_type": "number",
                        }
                    ],
                }
            )
    payload = {
        "schema_version": "ledger.source_package.v1",
        "package_id": "census-acs-s1501-state-attainment-2024",
        "label": "Census ACS 2024 S1501 state population by educational attainment",
        "dimension_labels": {"educational_attainment": "Educational attainment"},
        "artifact": {
            "source_name": "census_acs",
            "source_table": "ACS 2024 1-year subject table S1501 state educational attainment",
            "resource_package": "db",
            "resource_directory": "data/census/acs_s1501_state_2024",
            "manifest": "manifest.yaml",
            "vintage": "acs_1_year_{year}",
            "extracted_at": "2026-10-12",
            "extraction_method": (
                "data.census.gov table API JSON parsed and unpivoted to state "
                "age-universe by educational-attainment rows"
            ),
            "parser": "census_acs_s1501_attainment_json_rows",
            "sheet_name": "api_response",
        },
        "record_sets": record_sets,
    }

    class Dumper(yaml.SafeDumper):
        def ignore_aliases(self, data):
            return True

    OUT.parent.mkdir(parents=True, exist_ok=True)
    body = yaml.dump(
        payload, Dumper=Dumper, sort_keys=False, width=88, allow_unicode=True
    )
    OUT.write_text(HEADER + body, encoding="utf-8", newline="\n")
    facts = sum(len(rs["rows"]) for rs in record_sets)
    print(
        f"{OUT.relative_to(ROOT).as_posix()}: {len(record_sets)} record sets, {facts} facts"
    )


if __name__ == "__main__":
    main()
