def with_dimensions(target: dict, dims: list[tuple[str, str, str]]) -> dict:
    """Attach filters and constraints for (variable, value, label) triples."""
    filters: dict = {}
    constraints: list = []
    for variable, value, label in dims:
        filters[variable] = value
        constraints.append(constraint(variable, value, label))
    if filters:
        target["filters"] = filters
        target["constraints"] = constraints
    return target


