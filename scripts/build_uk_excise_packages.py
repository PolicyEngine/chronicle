def obr_excise_blocks() -> str:
    cells = source_cells_from_xlsx(
        OBR_RECEIPTS_XLSX.read_bytes(), artifact_meta(OBR_RECEIPTS_XLSX)
    )
    grids = {
        sheet: sheet_grid(cells, sheet)
        for sheet in ("3.1", "3.2", "3.8", "3.10", "3.11", "3.12")
    }
    # Sheet 3.10 states no basis. Its total is sheet 3.1's accrued betting and gaming
    # line, year for year, and differs from sheet 3.8's cash line.
    sheet_3_1 = grids["3.1"]
    assert sheet_3_1[(7, "B")] == "Betting and gaming taxes"
    assert sheet_3_1[(17, "B")] == "Note: All taxes are on an accrued basis."
    for index, column in enumerate("CDEFGH"):
        assert sheet_3_1[(5, chr(ord("D") + index))] == fy_label(2025 + index)
        assert grids["3.10"][(6, column)] == sheet_3_1[(7, chr(ord("D") + index))]
    assert grids["3.10"][(5, "C")] == "2025-26"
    assert grids["3.10"][(6, "C")] != grids["3.8"][(36, "E")]
    blocks = []
    for line in OBR_EXCISE_LINES:
        table = OBR_EXCISE_TABLES[line[0]]
        grid = grids[table["sheet"]]
        years = check_table(grid, table)
        row, header = line[1], line[2]
        assert grid[(row, "B")] == header, (line[0], row, grid.get((row, "B")))
        for opening, column in years:
            assert isinstance(grid[(row, column)], (int, float)), (line[0], row, column)
            blocks.append(dump([obr_excise_record(table, line, opening, column)]))
    return OBR_EXCISE_MARKER + "".join(blocks)


def build_obr_excise() -> None:
    """Insert (or replace) the excise record sets before the sheet 3.7 block."""
    text = OBR_RECEIPTS_YAML.read_text(encoding="utf-8")
    if OBR_EXCISE_HEADER not in text:
        head, schema, rest = text.partition("schema_version:")
        assert schema, "receipts package has no schema_version line"
        text = head.rstrip("\n") + "\n" + OBR_EXCISE_HEADER + schema + rest
    if OBR_LABELS_BEFORE in text:
        text = text.replace(OBR_LABELS_BEFORE, OBR_LABELS_AFTER)
    assert OBR_LABELS_AFTER in text, "receipts package labels are not the expected ones"
    before, marker, after = text.partition(OBR_EXCISE_MARKER)
    if not marker:
        before, marker, after = text.partition(OBR_3_7_MARKER)
        assert marker, "receipts package has no sheet 3.7 block"
        after = marker + after
    else:
        _old, sheet_3_7, tail = after.partition(OBR_3_7_MARKER)
        assert sheet_3_7, "receipts package has no sheet 3.7 block"
        after = sheet_3_7 + tail
    if not before.endswith("\n"):
        before += "\n"
    OBR_RECEIPTS_YAML.write_text(before + obr_excise_blocks() + after, encoding="utf-8")


