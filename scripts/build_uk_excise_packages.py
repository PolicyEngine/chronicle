def alcohol_record_set(
    *,
    sheet: str,
    product: str,
    family: str,
    kind: str,
    year: int,
    suffix: str,
    label: str,
    row: int,
    row_guards: list[dict],
    measures: list[dict],
) -> dict:
    record_set_id = f"{ALCOHOL_PREFIX}.{product}.{family}.{suffix}"
    if family == "clearances":
        start = ALCOHOL_NEW_REGIME_START if year == 2023 else None
        coverage = hmrc_coverage(
            kind,
            year,
            label,
            start=start,
            notes=(
                "Clearances under the Alcohol Duty regime introduced in August 2023 "
                "only; this year starts on 1 August 2023."
                if start
                else None
            ),
        )
        entity = {
            "entity": "institutional_sector",
            "entity_role": "alcohol_market",
            "domain": "alcohol_clearances",
        }
    elif family == "production":
        coverage = hmrc_coverage(kind, year, label)
        entity = {
            "entity": "institutional_sector",
            "entity_role": "uk_alcohol_producers",
            "domain": "alcohol_production",
        }
    else:
        coverage = hmrc_coverage(kind, year, label, accounting_basis="cash")
        entity = RECEIPTS_ENTITY
    row_spec = with_dimensions(
        {
            "value_id": product,
            "label": ALCOHOL_PRODUCTS[product],
            "ordinal": 0,
            "row_number": row,
            "expected_row_header_column": "A",
            "expected_row_header": label if kind == "fiscal_year" else year,
            "table_record_kind": "total" if product == "all" else "detail",
            "guard_cells": row_guards,
        },
        [("alcohol_product", product, "Alcohol product")],
    )
    record = {
        "record_set_id": record_set_id,
        "provenance_class": "administrative",
        "assertion": "observation",
        "record_set_spec_id": f"{record_set_id}.v1",
        "source_record_id_prefix": record_set_id,
        "sheet_name": sheet,
        "period_type": kind,
        "period": year,
        "period_coverage": coverage,
        **UK_GEOGRAPHY,
        **entity,
        "groupby_dimension": "hmrc.alcohol_product",
        "rows": [row_spec],
        "measures": measures,
    }
    if family == "receipts":
        record["shared_filters"] = {"accounting_basis": "cash"}
        record["shared_constraints"] = [
            constraint("accounting_basis", "cash", ACCOUNTING_BASIS_LABEL)
        ]
    return record


