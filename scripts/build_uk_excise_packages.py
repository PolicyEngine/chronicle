"""Author the chronicle#381 excise fact packages from their pinned publisher artifacts.

PolicyEngine/microcosm#1359 gives households alcohol and tobacco quantities levelled
to published clearances and checks them against duty receipts. This script writes,
from the bytes the manifests pin under ``db/data``, nothing downloaded and no fact
built:

- the OBR EFO March 2026 receipts package's excise lines: sheet 3.8's tobacco,
  spirits, wine, beer and cider, and betting and gaming duties and vaping tax (cash
  basis); sheet 3.10's betting and gaming duties by duty (forecast years only, accrued
  basis); sheet 3.11's tobacco clearances; sheet 3.12's alcohol clearances and accrued
  alcohol receipts; and sheet 3.2's three gambling lines.

Selectors are located by matching publisher text in the parsed source cells, and
every match is asserted, so a re-run against different bytes fails rather than
drifting.
"""

from __future__ import annotations

import re
from pathlib import Path

import yaml

from chronicle.sources.cells import (
    SourceArtifactMetadata,
    source_cells_from_ods,
    source_cells_from_xlsx,
)

ROOT = Path(__file__).resolve().parents[1]


class PackageDumper(yaml.SafeDumper):
    """Emit plain YAML with no anchors, so every record set reads alone."""

    def ignore_aliases(self, data: object) -> bool:
        return True


def dump(payload: object) -> str:
    return yaml.dump(
        payload,
        Dumper=PackageDumper,
        sort_keys=False,
        allow_unicode=True,
        width=100,
    )


def constraint(variable: str, value: object, label: str, operator: str = "==") -> dict:
    """Carry a publisher classification as a first-class constraint."""
    return {"variable": variable, "operator": operator, "value": value, "label": label}


def fy_label(opening_year: int) -> str:
    return f"{opening_year}-{str(opening_year + 1)[2:]}"


def sheet_grid(cells: list, sheet: str) -> dict[tuple[int, str], object]:
    """Map (row, column letter) to the raw value of one parsed sheet."""
    grid = {}
    for cell in cells:
        if cell.sheet_name == sheet and cell.raw_value not in (None, ""):
            column = re.match(r"[A-Z]+", cell.address).group(0)
            grid[(cell.row_number, column)] = cell.raw_value
    assert grid, f"sheet {sheet!r} is empty or missing"
    return grid


def artifact_meta(path: Path) -> SourceArtifactMetadata:
    return SourceArtifactMetadata(
        source_name="x",
        source_table="x",
        source_file=path.name,
        url=None,
        vintage="x",
        sha256="0",
        size_bytes=0,
        extracted_at="x",
        extraction_method="x",
    )


