def note_cell(grid: dict, column: str, fragment: str) -> tuple[int, str]:
    """Locate the one note in ``column`` that contains ``fragment``."""
    matches = [
        (row, text)
        for (row, col), text in grid.items()
        if col == column and isinstance(text, str) and fragment in text
    ]
    assert len(matches) == 1, (fragment, matches)
    return matches[0]


