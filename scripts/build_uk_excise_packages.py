def gc_quarters(grid: dict, row: int, opening: int) -> list[int]:
    """Rows of the year's quarters, which some tables print just above its total."""
    rows = []
    for candidate in range(row - 4, row):
        match = GC_QUARTER.fullmatch(str(grid.get((candidate, "A"))))
        if match:
            year = int(match.group(2))
            expected = opening + 1 if match.group(1) == "Jan - Mar" else opening
            if year == expected:
                rows.append(candidate)
    return rows


def gc_not_measured(
    grid: dict, columns: tuple, annual_rows: dict[int, int]
) -> dict[tuple[int, str], str]:
    """Published zeros that stand for no measurement, by (row, column), with why.

    - a column zero in every financial year (bingo machines' and peer-to-peer poker's
      turnover, betting exchanges' turnover): the Commission reports no turnover there;
    - a year's zero whose quarters are all '-' (not available);
    - zero sales by channel against a positive total, where no channel split exists.
    """
    reasons = {}
    for column, _header, metric, _dims in columns:
        values = [grid.get((row, column)) for row in annual_rows.values()]
        numbers = [v for v in values if isinstance(v, (int, float))]
        if numbers and all(v == 0 for v in numbers):
            for row in annual_rows.values():
                if grid.get((row, column)) == 0:
                    reasons[row, column] = "zero in every financial year"
    for opening, row in annual_rows.items():
        quarters = gc_quarters(grid, row, opening)
        for column, *_ in columns:
            if grid.get((row, column)) == 0 and len(quarters) == 4:
                if all(grid.get((q, column)) == "-" for q in quarters):
                    reasons[row, column] = "zero, with every quarter '-'"
        channels = [
            column
            for column, _header, metric, dims in columns
            if metric == "sales" and dims.get("sales_channel", "all") != "all"
        ]
        totals = [
            column
            for column, _header, metric, dims in columns
            if metric == "sales" and dims.get("sales_channel", "all") == "all"
        ]
        if channels and all(grid.get((row, c)) == 0 for c in channels):
            assert all(grid.get((row, c), 0) > 0 for c in totals), (row, totals)
            for column in channels:
                reasons[row, column] = "zero by channel against a positive total"
    return reasons


def gc_remote_regime_note(grids: dict, opening: int) -> str | None:
    """Sheet 1's remote lines before 2015-16 follow the pre-November 2014 regime."""
    if opening > 2014:
        return None
    sheet_1, sheet_12, sheet_10 = grids["1"], grids["12"], grids["10"]
    rows_1 = {
        int(m.group(1)): r
        for (r, c), v in sheet_1.items()
        if c == "A" and (m := GC_YEAR.fullmatch(str(v)))
    }
    # Sheet 12 repeats its year labels in three tables; the first is the general one.
    rows_12 = {}
    for (r, c), v in sorted(sheet_12.items()):
        if c == "A" and isinstance(v, str):
            rows_12.setdefault(v, r)
    number = lambda v: v if isinstance(v, (int, float)) else 0.0  # noqa: E731
    if opening <= 2013:
        r12 = rows_12[f"Apr {opening} - Mar {opening + 1}"]
        parts = {"I": ("K", "L", "O"), "J": ("M",), "K": ("N",)}
        for column, sources in parts.items():
            expected = sum(number(sheet_12[(r12, s)]) for s in sources)
            assert abs(sheet_1[(rows_1[opening], column)] - expected) < 1e-6, (
                opening,
                column,
            )
        return (
            "Sheet 1's remote lines for this year, and the totals that hold them, cover "
            "remote gambling before the November 2014 legislation: they equal sheet 12 "
            "('Remote: Pre Nov 2014 Legislation')."
        )
    r12 = rows_12["Apr 2014 - Oct 2014"]
    r10 = next(
        r for (r, c), v in sheet_10.items() if c == "A" and v == "Nov 2014 - Mar 2015"
    )
    parts = {"I": (("K", "L", "O"), "I"), "J": (("M",), "J"), "K": (("N",), "K")}
    for column, (sources, remote) in parts.items():
        expected = (
            sum(number(sheet_12[(r12, s)]) for s in sources) + sheet_10[(r10, remote)]
        )
        assert abs(sheet_1[(rows_1[opening], column)] - expected) < 1e-6, column
    return (
        "Sheet 1's remote lines for 2014-15 span the November 2014 legislation: they add "
        "sheet 12's April to October 2014 to sheet 10's November 2014 to March 2015."
    )


