MONTH_ROW = re.compile(rf"({'|'.join(MONTH_NAMES)}) (\d{{4}})(?: \[[a-z]+\])?")


def tobacco_months(grid: dict, columns: tuple) -> dict[tuple[int, int], tuple]:
    """Map (year, month) to (row, label, published) for the sheet's monthly table.

    ``published`` says whether every emitted column holds a number that month; the
    first month, January 1991, has '[X]' receipts.
    """
    months = {}
    for (row, column), label in grid.items():
        match = MONTH_ROW.fullmatch(str(label)) if column == "A" else None
        if match:
            month = MONTH_NAMES.index(match.group(1)) + 1
            published = all(
                isinstance(grid.get((row, code)), (int, float)) for code, *_ in columns
            )
            months[int(match.group(2)), month] = (row, label, published)
    assert months, "no monthly table"
    return months


def tobacco_part_year(
    grid: dict, columns: tuple, months: dict, kind: str, year: int, row: int
) -> tuple[str | None, str | None, list]:
    """Start date, note and guards for a year the monthly table covers only in part.

    The monthly tables start in January 1991, so a year whose first months they lack
    (or mark '[X]') is a part year: its annual figure must equal the months published,
    which the check below asserts before the year's coverage is narrowed.
    """
    if kind == "fiscal_year":
        period = [(year, month) for month in range(4, 13)] + [
            (year + 1, month) for month in range(1, 4)
        ]
    else:
        period = [(year, month) for month in range(1, 13)]
    published = [ym for ym in period if ym in months and months[ym][2]]
    if published and published[0] == period[0]:
        return None, None, []
    assert published, (kind, year)
    first, last = published[0], published[-1]
    assert published == period[period.index(first) : period.index(last) + 1]
    for code, *_ in columns:
        months_sum = sum(grid[(months[ym][0], code)] for ym in published)
        assert abs(months_sum - grid[(row, code)]) <= 1e-6 * max(1, abs(months_sum)), (
            kind,
            year,
            code,
        )
    earliest = min(months)
    first_row, first_label, _ = months[earliest]
    guards = [guard("A", first_row, first_label, "first month of the monthly table")]
    marked = [ym for ym in period if ym in months and not months[ym][2]]
    if marked:
        marked_row = months[marked[0]][0]
        guards.append(
            guard(
                columns[0][0],
                marked_row,
                grid[(marked_row, columns[0][0])],
                "month not available",
            )
        )
    start = f"{first[0]}-{first[1]:02d}-01"
    note = (
        f"The monthly table starts in {MONTH_NAMES[earliest[1] - 1]} {earliest[0]}"
        + (
            f" and marks {MONTH_NAMES[marked[0][1] - 1]} {marked[0][0]} '[X]' (not available)"
            if marked
            else ""
        )
        + f", so this year covers {MONTH_NAMES[first[1] - 1]} {first[0]} to "
        f"{MONTH_NAMES[last[1] - 1]} {last[0]} only; its figure equals those months'."
    )
    return start, note, guards


