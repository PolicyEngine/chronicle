def hmrc_period(kind: str, value: int | str) -> tuple[int, str, str]:
    """(opening or calendar year, record-set suffix, publisher label) of one row."""
    if kind == "fiscal_year":
        match = re.fullmatch(r"(\d{4}) to (\d{4})(?: \[[a-z]+\])?", str(value))
        assert match and int(match.group(2)) == int(match.group(1)) + 1, value
        return int(match.group(1)), f"fy{match.group(1)}", str(value)
    match = re.fullmatch(r"(\d{4})(?: \[[a-z]+\])?", str(value))
    assert match, value
    return int(match.group(1)), f"cy{match.group(1)}", str(value)


