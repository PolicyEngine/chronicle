"""Author the chronicle#381 excise fact packages from their pinned publisher artifacts.

PolicyEngine/microcosm#1359 gives households alcohol and tobacco quantities levelled
to published clearances and checks them against duty receipts. This script writes,
from the bytes the manifests pin under ``db/data``, nothing downloaded and no fact
built:

- the OBR EFO March 2026 receipts package's excise lines: sheet 3.8's tobacco,
  spirits, wine, beer and cider, and betting and gaming duties and vaping tax (cash
  basis); sheet 3.10's betting and gaming duties by duty (forecast years only, accrued
  basis); sheet 3.11's tobacco clearances; sheet 3.12's alcohol clearances and accrued
  alcohol receipts; and sheet 3.2's three gambling lines.
- the HMRC Alcohol Bulletin, Tobacco Bulletin and UK Betting and Gaming Statistics
  packages, and the Gambling Commission industry statistics package.
- the Gambling Commission's GSGB 2025 participation tables (B.1 to B.4, B.9, B.10 and
  B.13), for PolicyEngine/microcosm#1381. That workbook is stored in R2 only, so this
  reads it through the source-artifact cache (read_registered_artifact).

The 30 September 2026 Consumer Trends edition chronicle#381 also asks for comes
from scripts/build_uk_consumption_tax_packages.py, which needs that package's own
YAML (see its docstring).

Selectors are located by matching publisher text in the parsed source cells, and
every match is asserted, so a re-run against different bytes fails rather than
drifting.
"""

from __future__ import annotations

