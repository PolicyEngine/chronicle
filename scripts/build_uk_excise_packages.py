    cells = parse_cells(path)
    preface_sheet, preface_row, preface_column = GC_PREFACE_CELL
    preface = sheet_grid(cells, preface_sheet)[(preface_row, preface_column)]
    # Every fact, the National Lottery's included, is stamped as this says.
    assert "the gambling industry in Great Britain" in preface, preface
