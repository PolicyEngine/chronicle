"""Regenerate the four matched SOI filing-season Table 1 source packages.

Run from any directory after acquiring the pinned publisher workbooks with
Chronicle fetch-artifact. The generated YAML uses native Chronicle selectors:
each IRS line is one measure, and its columns are one total and 16 AGI bands.
"""

