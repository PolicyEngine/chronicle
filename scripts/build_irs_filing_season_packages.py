import json
import re
from datetime import date
from pathlib import Path

import openpyxl
import yaml

ROOT = Path(__file__).resolve().parents[1]
PACKAGES = ROOT / "packages" / "irs_soi"
AGI = "us:statutes/26/62#adjusted_gross_income"
VINTAGES = {
    (2024, 21): (
        "2025-05-22",
        "4a20b0c67e9296c2c401b43deb7bcc4f7fa54925266f43d72e379687e2d57051",
    ),
    (2024, 30): (
        "2025-07-24",
        "59bcc4f111cd7ef51bd3a5c36442d0d6c87f5f269399154bb0a0a20e4cc49387",
    ),
    (2025, 21): (
        "2026-05-28",
        "c2bb465f6c12eaa5d1eb8cfb9132b8c14b5619655d5e9c5810fb45b5d763312c",
    ),
    (2025, 30): (
        "2026-07-30",
        "c36eda3e737c0b9b77e0c46f53e134158b4e1584fdb7d9968d8a82bf0416035c",
    ),
}

# Reuse the existing SOI measure IDs when these lines have the same meaning.
# Leave similarly named but distinct series, e.g. tax due at filing, separate.
MEASURE_NAMES = {
    "Total wages": "wages_salaries",
    "Taxable income from Individual Retirement Arrangement (IRA)": "taxable_ira_distributions",
    "Taxable income from pensions, and annuities": "taxable_pension_income",
    "Taxable social security benefits": "taxable_social_security",
    "Net capital gains / losses": "net_capital_gains",
    "Business net income / loss (Schedule C)": "schedule_c_income",
    "Total standard deduction": "standard_deduction",
    "State and local taxes deduction after limitation": "limited_state_local_taxes",
    "Total charitable contributions deduction": "charitable",
    "Total premium tax credit": "premium_tax_credit",
    "Earned income credit": "total_earned_income_credit",
}
CONCEPTS = {
    "return_count": "irs_soi.individual_income_tax_returns",
    "adjusted_gross_income": AGI,
    "total_itemized_deductions_returns": "irs_soi.returns_with_itemized_deductions",
    "total_itemized_deductions_amount": "irs_soi.total_itemized_deductions",
    "limited_state_local_taxes_amount": "irs_soi.limited_state_local_taxes",
    "standard_deduction_amount": "irs_soi.standard_deduction",
    "total_earned_income_credit_returns": "irs_soi.returns_with_total_earned_income_credit",
    "total_earned_income_credit_amount": "irs_soi.total_earned_income_credit",
}


def indicators(sheet):
    """Yield the 116 count/amount measures; a bare Amount inherits its heading."""
    for row in range(11, 127):
        header = sheet.cell(row, 1).value
        text = " ".join(header.split())
        if text == "Amount":
            text = " ".join(sheet.cell(row - 1, 1).value.split())
            unit = "usd"
        else:
            unit = "usd" if row in (13, 64) else "count"
        label = re.sub(r"\s*\[\d+\]", "", text.split(":")[0])
        stem = MEASURE_NAMES.get(
            label, re.sub(r"[^a-z0-9]+", "_", label.lower()).strip("_")
        )
        measure = {
            11: "return_count",
            12: "electronically_filed_returns",
            13: "adjusted_gross_income",
        }.get(row)
        if measure is None:
            measure = stem + ("_returns" if unit == "count" else "_amount")
        yield row, header, label, measure, unit


def declare(mapping, indent=0):
    text = yaml.safe_dump(mapping, sort_keys=False, width=1000, allow_unicode=True)
    return "\n".join(
        (" " * indent + line) if line else "" for line in text.rstrip().splitlines()
    )


def package_yaml(year, week, cutoff, workbook, bands):
    sheet = workbook["Filing Season"]
    title = sheet["A1"].value
    date_label = date.fromisoformat(cutoff).strftime("%B %-d, %Y")
    if f"Tax Year {year}" not in title or f"Cycle {week}, {date_label}" not in title:
        raise ValueError(f"Unexpected publication title: {title}")
    scope = next(row[0] for row in sheet.values if str(row[0]).startswith("[1]"))
    domain = "current_tax_year_individual_returns_initially_processed_by_filing_season_cutoff"
    prefix = f"irs_soi.ty{year}.filing_season_week{week}.all_returns"
    package_id = f"soi-filing-season-week{week}-{year}"
    lines = [
        "# Generated by scripts/build_irs_filing_season_packages.py.",
        declare(
            {
                "schema_version": "chronicle.source_package.v2",
                "package_id": package_id,
                "label": f"IRS SOI filing season cycle {week}, tax year {year}",
                "dimension_labels": {
                    "income_range": "Income range",
                    AGI: "Adjusted gross income",
                    "filing_season_week": "Filing season processing cycle",
                    "processing_cutoff": "IRS processing cutoff",
                },
                "dimension_value_labels": {
                    "income_range": {
                        "200k_to_250k": "$200,000 under $250,000",
                        "250k_to_500k": "$250,000 under $500,000",
                    }
                },
                "artifact": {
                    "source_name": "irs_soi",
                    "source_table": "Filing Season Statistics Table 1",
                    "resource_package": "db",
                    "resource_directory": f"data/irs_soi/filing_season_week{week}_{year}",
                    "manifest": "manifest.yaml",
                    "vintage": f"filing_season_{year + 1}_week_{week}_tax_year_{year}",
                    "extracted_at": "2026-11-18",
                    "extraction_method": "openpyxl whole-workbook used-range cell parse",
                    "parser": "xlsx_used_range",
                    "artifact_year": year,
                },
            }
        ),
        "record_set_defaults: &record_set",
        declare(
            {
                "source_record_id_prefix": prefix,
                "provenance_class": "administrative",
                "sheet_name": "Filing Season",
                "period_type": "tax_year",
                "period": year,
                "geography_id": "0100000US",
                "geography_level": "country",
                "geography_name": "United States",
                "geography_vintage": "2020_census",
                "entity": "tax_unit",
                "entity_role": "filing_unit",
                "domain": domain,
                "groupby_dimension": AGI,
                "shared_filters": {
                    "filing_season_week": week,
                    "processing_cutoff": cutoff,
                },
                "shared_constraints": [
                    {"variable": "filing_season_week", "operator": "==", "value": week},
                    {
                        "variable": "processing_cutoff",
                        "operator": "==",
                        "value": cutoff,
                    },
                ],
                "period_coverage": {
                    "basis": "tax",
                    "source_period_label": " ".join(title.split())
                    .split("(through ")[1]
                    .split(")")[0],
                    "notes": " ".join(scope.split()),
                },
            },
            2,
        ),
        "column_defaults:",
    ]
    for column, band in enumerate(bands, 2):
        lines.append(f"  - &col{column}")
        lines.append(declare(band, 4))
    money_note = sheet["A2"].value
    if money_note != "(Money amounts are in thousands of dollars)":
        raise ValueError(money_note)
    lines.extend(
        [
            "guard_defaults:",
            f"  - &title {{column: A, row: 1, expected_value: {json.dumps(title)}, label: table title}}",
            f"  - &units {{column: A, row: 2, expected_value: {json.dumps(money_note)}, label: published dollar scale}}",
            "record_sets:",
        ]
    )
    for row, header, label, name, unit in indicators(sheet):
        lines.extend(
            [
                "  - <<: *record_set",
                f"    record_set_id: {prefix}.{name}",
                f"    record_set_spec_id: irs_soi.filing_season.{name}.v1",
                "    rows:",
                f"      - &row{row}",
                "        <<: *col2",
                f"        row_number: {row}",
                "        expected_row_header_column: A",
                f"        expected_row_header: {json.dumps(header)}",
            ]
        )
        guards = ["*title", "*units"]
        if header.strip() == "Amount":
            parent_header = sheet.cell(row - 1, 1).value
            guards.append(
                f"{{column: A, row: {row - 1}, expected_value: {json.dumps(parent_header)}, label: amount heading}}"
            )
        lines.append("        guard_cells: [" + ", ".join(guards) + "]")
        for column in range(3, 19):
            # Leftmost map wins in YAML merges. The AGI column overrides col2,
            # while the selected IRS line supplies its row and header guards.
            lines.append(f"      - {{<<: [*col{column}, *row{row}]}}")
        concept = CONCEPTS.get(name, "irs_soi.filing_season." + name)
        lines.extend(["    measures:", f"      - measure_id: {name}"])
        lines.append(
            declare(
                {
                    "label": label + (" (returns)" if unit == "count" else " (amount)"),
                    "ordinal": 0,
                    "column": "B",
                    "concept": concept,
                    "unit": unit,
                    "aggregation": "sum",
                    "value_scale": 1000 if unit == "usd" else 1,
                    "expected_cell_type": "number",
                },
                8,
            )
        )
    return "\n".join(lines) + "\n"


def agi_columns():
    """Use the same income-band identities and bounds as SOI's cycle-47 table."""
    existing = yaml.safe_load(
        (PACKAGES / "filing_season_week47_2024/source_package.yaml").read_text()
    )
    all_returns = {
        "value_id": "all",
        "label": "Total returns",
        "column": "B",
        "source_column_id": "total_returns",
        "expected_column_header_row": 4,
        "expected_column_header": "Total\nreturns",
        "filters": {"income_range": "all"},
        "constraints": [],
        "table_record_kind": "total",
        "ordinal": 0,
    }
    columns = [all_returns]
    for ordinal, row in enumerate(existing["record_sets"][2]["rows"], 1):
        keys = (
            "value_id",
            "label",
            "column",
            "source_column_id",
            "expected_column_header_row",
            "expected_column_header",
            "filters",
            "constraints",
        )
        columns.append(
            {
                **{key: row[key] for key in keys},
                "ordinal": ordinal,
                "table_record_kind": "detail",
            }
        )
    return columns


if __name__ == "__main__":
    bands = agi_columns()
    for (year, week), (cutoff, checksum) in VINTAGES.items():
        directory = f"filing_season_week{week}_{year}"
        artifact = (
            ROOT / "db/data/irs_soi" / directory / f"{year - 1999}inweek{week}.xlsx"
        )
        if hashlib.sha256(artifact.read_bytes()).hexdigest() != checksum:
            raise ValueError(f"Publisher bytes changed: {artifact}")
        workbook = openpyxl.load_workbook(artifact, data_only=True)
        destination = PACKAGES / directory
        destination.mkdir(exist_ok=True)
        (destination / "source_package.yaml").write_text(
            package_yaml(year, week, cutoff, workbook, bands)
        )
        workbook.close()
